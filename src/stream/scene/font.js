export function textMaskTiny(text) {
  const glyphs = [...text.toUpperCase()].map((ch) => TINY_PARSED[ch] ?? TINY_PARSED[' ']);
  const width = glyphs.reduce((w, g) => w + g[0].length + 1, -1);
  const mask = Array.from({ length: 5 }, () => Array.from({ length: Math.max(0, width) }, () => false));
  let x = 0;
  for (const g of glyphs) {
    for (let y = 0; y < 5; y++) for (let gx = 0; gx < g[y].length; gx++) if (g[y][gx]) mask[y][x + gx] = true;
    x += g[0].length + 1;
  }
  return mask;
}
