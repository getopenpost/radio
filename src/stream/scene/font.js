/** Text as a boolean mask, one pixel between letters. Unknown characters become spaces. */
export function textMask(text) {
  const glyphs = [...text.toUpperCase()].map((ch) => PARSED[ch] ?? PARSED[' ']);
  const width = glyphs.reduce((w, g) => w + g[0].length + 1, -1);
  const mask = Array.from({ length: 7 }, () => Array.from({ length: Math.max(0, width) }, () => false));
  let x = 0;
  for (const g of glyphs) {
    for (let y = 0; y < 7; y++) for (let gx = 0; gx < g[y].length; gx++) if (g[y][gx]) mask[y][x + gx] = true;
    x += g[0].length + 1;
  }
  return mask;
}

