def resolve(v):
    rgb = oklch(*v[1:]) if isinstance(v, tuple) and v[0] == 'oklch' else hex_rgb(v)
    return '#%02x%02x%02x' % rgb

def emit(table):
    lines = []
    for name in SLOTS:
        lines.append('    Color("%s"),' % resolve(table[name]))
    return '\n'.join(lines)

